create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  article_id integer not null check (article_id between 1 and 23),
  name text not null check (char_length(name) between 1 and 50),
  message text not null check (char_length(message) between 1 and 1000),
  created_at timestamptz not null default now()
);
alter table public.comments enable row level security;
drop policy if exists "Public can read comments" on public.comments;
create policy "Public can read comments" on public.comments for select using (true);
drop policy if exists "Anyone can post comments" on public.comments;
create policy "Anyone can post comments" on public.comments for insert with check (
  char_length(name) between 1 and 50 and char_length(message) between 1 and 1000
);
grant select, insert on public.comments to anon, authenticated;
grant usage, select on sequence public.comments_id_seq to anon, authenticated;
